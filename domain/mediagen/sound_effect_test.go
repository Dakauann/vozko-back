const soundModel = "bytedance-seed/seed-audio-1-0"

func soundEffect() Request {
	return Request{WorkspaceID: "ws", Kind: KindSoundEffect, Model: soundModel, Prompt: "whoosh rápido de transição", DurationMS: 1_500}
}

func TestASoundEffectIsAGeneratedShortAudio(t *testing.T) {
	if err := soundEffect().Validate(); err != nil {
		t.Fatal(err)
	}
	storage, ok := KindSoundEffect.Storage()
	if !ok || storage.Type != media.MediaTypeAudio || storage.Extension != ".m4a" || storage.Folder != "audio" {
		t.Fatalf("storage %+v", storage)
	}
	if !KindSoundEffect.UsesModel() || KindSoundEffect.Topic() != Topic || KindSoundEffect.Reusable() {
		t.Fatal("a sound effect is generated by a model on the generation lane, every time it is asked")
	}
	found := false
	for _, kind := range GenerationKinds() {
		found = found || kind == KindSoundEffect
	}
	if !found {
		t.Fatal("a sound effect counts against the generation ceiling")
	}
}

func TestASoundEffectNeedsAPromptAModelAndALengthWithinBounds(t *testing.T) {
	cases := map[string]struct {
		change func(*Request)
		field  string
		code   string
	}{
		"no prompt":   {func(r *Request) { r.Prompt = "  " }, FieldPrompt, CodeRequired},
		"long prompt": {func(r *Request) { r.Prompt = strings.Repeat("a", MaxSoundEffectPromptRunes+1) }, FieldPrompt, CodeTooLong},
		"no model":    {func(r *Request) { r.Model = "" }, FieldModel, CodeRequired},
		"no length":   {func(r *Request) { r.DurationMS = 0 }, FieldDuration, CodeRequired},
		"too short":   {func(r *Request) { r.DurationMS = MinSoundEffectMS - 1 }, FieldDuration, CodeOutOfRange},
		"too long":    {func(r *Request) { r.DurationMS = MaxSoundEffectMS + 1 }, FieldDuration, CodeOutOfRange},
		"negative":    {func(r *Request) { r.DurationMS = -1_000 }, FieldDuration, CodeOutOfRange},
	}
	for name, c := range cases {
		req := soundEffect()
		c.change(&req)
		if got := codesOf(t, req.Validate())[c.field]; got != c.code {
			t.Errorf("%s: %s code %q", name, c.field, got)
		}
	}
	for _, ms := range []int{MinSoundEffectMS, MaxSoundEffectMS} {
		req := soundEffect()
		req.DurationMS = ms
		if err := req.Validate(); err != nil {
			t.Fatalf("%d ms is a valid length: %v", ms, err)
		}
	}
}

func TestOnlyASoundEffectCarriesALength(t *testing.T) {
	job, err := NewJob(Request{WorkspaceID: "ws", Kind: KindSoundEffect, Model: soundModel, Prompt: " impacto grave ", DurationMS: 800, Voice: "alloy", Aspect: AspectStory}, "u1")
	if err != nil {
		t.Fatal(err)
	}
	want := Request{WorkspaceID: "ws", Kind: KindSoundEffect, Model: soundModel, Prompt: "impacto grave", DurationMS: 800}
	if !reflect.DeepEqual(job.Request(), want) || job.DurationMS != 800 {
		t.Fatalf("request %+v", job.Request())
	}
	music, err := NewJob(Request{WorkspaceID: "ws", Kind: KindMusic, Model: audioModel, Prompt: "samba", DurationMS: 800}, "u1")
	if err != nil {
		t.Fatal(err)
	}
	if music.DurationMS != 0 {
		t.Fatalf("music keeps no length, got %d", music.DurationMS)
	}
}

func TestTheLengthOfASoundEffectIsPartOfItsFingerprint(t *testing.T) {
	short, long := soundEffect(), soundEffect()
	long.DurationMS = 3_000
	if short.Fingerprint("u1") == long.Fingerprint("u1") {
		t.Fatal("two lengths of the same effect are two generations")
	}
	music := Request{WorkspaceID: "ws", Kind: KindMusic, Model: audioModel, Prompt: "samba"}
	withLength := music
	withLength.DurationMS = 3_000
	if music.Fingerprint("u1") != withLength.Fingerprint("u1") {
		t.Fatal("a length a kind ignores does not change its fingerprint")
	}
}

